import assert from 'node:assert/strict';
import fs from 'node:fs';
const games=JSON.parse(fs.readFileSync('data/games.json','utf8'));
const allowed=new Set(['Food Wheel','Jackpot','Slots','Board','Arcade','Battle','Roulette']);
const expected=['lion_food','night_food','jackpot_fruit','slots','sovera_gaddy','sovera_food','carrom','greedy_wheel'];
assert.deepEqual(games.slice(0,8).map(x=>x.id),expected,'Preserve the original eight games in order');
assert.equal(games.length,12,'Unified catalogue must have twelve games');
assert.deepEqual(games.slice(8).map(x=>x.id),['royal_crystal_run_3d','royal_battle_3d','royal_slots_3d','royal_roulette_3d']);
for (const game of games){
 assert.ok(game.name&&game.description&&game.symbol);
 assert.ok(allowed.has(game.category));
}
const html=fs.readFileSync('index.html','utf8');
const script=fs.readFileSync('assets/site.js','utf8');
assert.ok(html.includes('Play Original Games'));
assert.ok(html.includes('Manual USD')||html.includes('payment'));
assert.ok(script.includes('data/games.json'));
assert.ok(script.includes('game.play_url') && script.includes('originalLink'),'Catalog cards must route standalone demos and originals correctly');
for(const p of ['demos/royal-slots-3d/index.html','demos/royal-roulette-3d/index.html','assets/royal-casino-v2.js','assets/royal-casino-v2.css','services/practice-api.js','services/migrations/0001_practice.sql'])assert.ok(fs.existsSync(p),'Missing playable practice casino file: '+p);
const royalClient=fs.readFileSync('assets/royal-casino-v2.js','utf8');
const royalApi=fs.readFileSync('services/practice-api.js','utf8');
assert.ok(royalClient.includes('function place(') && royalClient.includes('function renderTicket(') && royalClient.includes('function rouletteAnimate('),'Roulette multiple-chip betting board must exist');
assert.ok(royalClient.includes('async function play(') && royalClient.includes('/api/spin'),'Client must post server-verified free rounds');
assert.ok(royalApi.includes('function payoutSlot(') && royalApi.includes('function rouletteMultiplier('),'Server payout rules must exist');
assert.ok(royalApi.includes('crypto.getRandomValues') && royalApi.includes('env.DB.batch') && royalApi.includes('request_id'),'Server randomness and atomic/idempotent D1 settlement must exist');
assert.ok(script.includes('/demo'));
assert.ok(html.includes('12 GAMES'),'Unified game hub must display twelve game entries');
const demo=fs.readFileSync('demos/royal-crystal-run-3d/index.html','utf8');
assert.ok(demo.includes('Royal Crystal Run 3D') && demo.includes('id="game"'),'Playable WebGL game must exist');
assert.ok(demo.includes("const LEVELS=[") && demo.includes("'CRYSTAL EMPEROR'") && demo.includes("'FIRE GUARDIAN'"),'10-stage campaign and bosses must exist');
assert.ok(demo.includes('function stageCheck()') && demo.includes('function boss3D()'),'Campaign and boss gameplay functions must exist');
assert.ok(demo.includes('DAILY=') && demo.includes('RANKING · THIS DEVICE'),'Missions and local ranking must exist');
const battle=fs.readFileSync('demos/royal-battle-3d/index.html','utf8');
assert.ok(games.some(g=>g.id==='royal_battle_3d' && g.play_url.includes('soverix-royal-battle-preview')),'Royal Battle preview must be linked');
assert.ok(battle.includes('function sword()') && battle.includes('function special()') && battle.includes('function dodge()'),'Playable sword, special and dodge actions must exist');
assert.ok(battle.includes('function spawnWave(') && battle.includes('function chooseUpgrade(') && battle.includes('SHADOW KING'),'Wave upgrades and boss must exist');
assert.ok(!html.includes('<script src="https://soverix-games-provider-staging.soverixnet.workers.dev/original/'));
console.log('Validated unified 12-game SOVERIX hub: eight originals, four standalone games and casino practice files.');
